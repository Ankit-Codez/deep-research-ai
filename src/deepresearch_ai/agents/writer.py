"""Writer node: render supported passages with application-owned citations."""

from deepresearch_ai.config import Settings
from deepresearch_ai.graph.state import ResearchState
from deepresearch_ai.models import ResearchReport
from deepresearch_ai.services.reporting import escape_markdown
from deepresearch_ai.agents.verification import insufficient
from deepresearch_ai.services.acquisition import source_capacity, source_shortfall, source_target


class WriterAgent:
    """Compose verified claim statements; evidence and citations stay deterministic.

    No new prose is generated by an LLM here. Source passages remain available
    separately in the report's evidence records and the dashboard Evidence tab.
    """

    def __init__(self, settings: Settings):
        self.settings = settings

    def __call__(self, state: ResearchState) -> dict[str, object]:
        sources = {source.source_id: source for source in state["sources"]}
        evidence = {item.evidence_id: item for item in state["evidence"]
                    if item.source_id in sources and item.excerpt in sources[item.source_id].content}
        claims = {claim.claim_id: claim for claim in state["claims"]}
        verifications = [result for result in state["verification_results"]
                         if result.claim_id in claims and result.claim == claims[result.claim_id].claim
                         and all(reference in evidence for reference in result.evidence_ids)
                         and all(item.evidence_id in result.evidence_ids for item in result.passage_assessments)
                         and len({item.evidence_id for item in result.passage_assessments}) == len(result.passage_assessments)
                         and (not result.source_ids or set(result.source_ids) == {
                             evidence[reference].source_id for reference in result.evidence_ids})]
        rejected_verifications = len(verifications) != len(state["verification_results"])
        # Recheck structured judgments at the final citation boundary as well.
        checked = []
        for result in verifications:
            supports = any(item.relation == "supports" for item in result.passage_assessments)
            contradicts = any(item.relation == "contradicts" for item in result.passage_assessments)
            assessed = {item.evidence_id for item in result.passage_assessments}
            if result.verdict == "supported" and (
                    not supports or contradicts or assessed != set(evidence)
                    or set(result.evidence_ids) != assessed):
                checked.append(insufficient(claims[result.claim_id], set(evidence)))
                rejected_verifications = True
            else:
                checked.append(result)
        verifications = checked
        verified_ids = {item.claim_id for item in verifications}
        # Rejected or unvisited claims stay visible as unresolved drafts.
        verifications.extend(insufficient(claim, set(evidence)) for claim in state["claims"]
                             if claim.claim_id not in verified_ids)
        uncertainties = [
            *state["uncertainties"],
            *(error.message for error in state["errors"]),
            "Verification is an LLM assessment of retrieved evidence, not independent verification of source truth.",
            "Multiple cited pages do not by themselves establish independent corroboration or source credibility.",
            f"At most {self.settings.research_max_content_chars} text characters per page were considered.",
        ]
        if self.settings.mock_mode:
            uncertainties.append("MOCK MODE: fixed local RAG samples; no live research was performed.")
        if not state["coverage_sufficient"]:
            uncertainties.append("The retrieved evidence does not adequately cover the research question.")
        if state["rejected_evidence"]:
            uncertainties.append("Unknown source IDs or non-verbatim passages were rejected.")
        if state["usage"].limit_reason:
            uncertainties.append(state["usage"].limit_reason)
        if source_shortfall(state, self.settings):
            uncertainties.append(
                f"Only {len(sources)} usable page(s) were retrieved; the target was {source_target(state, self.settings)}. "
                f"Stopped after {state['page_attempts']}/{self.settings.research_max_page_attempts} download attempts "
                f"and {state['source_retry_count']}/{self.settings.research_max_source_retries} source follow-up rounds, "
                "within the configured search and time budgets."
            )
        if not sources:
            uncertainties.append("No usable source pages were retrieved; search snippets were not used as evidence.")
        if source_capacity(state, self.settings) < 2:
            uncertainties.append("The configured usable-page cap is below the report's two-source requirement.")
        if any(result.verdict == "insufficient_evidence" for result in verifications):
            if state["retry_count"] >= self.settings.research_max_retries:
                uncertainties.append(f"Additional research limit reached ({state['retry_count']} follow-up rounds).")
            if state["page_attempts"] >= self.settings.research_max_page_attempts:
                uncertainties.append("The run-wide page-attempt limit left unresolved claims without further retrieval.")
            if len(sources) >= source_capacity(state, self.settings):
                uncertainties.append("The usable-page cap left no room for additional sources for unresolved claims.")
        if rejected_verifications:
            uncertainties.append("Invalid verification references were rejected by the writer.")

        citations = {}
        sentences = []
        examples = []
        for result in verifications:
            if result.verdict != "supported":
                continue
            labels = []
            for reference in result.evidence_ids:
                if not any(item.evidence_id == reference and item.relation == "supports"
                           for item in result.passage_assessments):
                    continue
                item = evidence[reference]
                label = next((label for label, sid in citations.items() if sid == item.source_id), None)
                if label is None:
                    label = str(len(citations) + 1)
                    citations[label] = item.source_id
                if label not in labels:
                    labels.append(label)
            if labels:
                text = result.claim if result.claim.endswith(('.', '?', '!')) else result.claim + '.'
                sentence = escape_markdown(text) + ' ' + ' '.join(f'[{label}]' for label in labels)
                (examples if claims[result.claim_id].relevance == 'context' else sentences).append(sentence)
        supported_source_ids = set(citations.values())
        paragraphs = [' '.join(sentences[index:index+2]) for index in range(0, len(sentences), 2)]
        if examples:
            uncertainties.append('Source-specific examples illustrate particular implementations; they do not establish universal practice.')
        for verdict in ("contradicted", "insufficient_evidence"):
            count = sum(result.verdict == verdict for result in verifications)
            if count:
                uncertainties.append(f"{count} claim(s) had verdict {verdict}; they were excluded from the supported summary.")
        unresolved = []
        optional = []
        for result in verifications:
            if result.verdict == "supported":
                continue
            text = f"- **{result.verdict}**: {escape_markdown(result.claim)} {escape_markdown(result.rationale)}"
            if result.disagreement:
                text += " Conflicting retrieved passages (source credibility has not been independently established):"
                for assessment in result.passage_assessments:
                    if assessment.relation == "irrelevant":
                        continue
                    item = evidence[assessment.evidence_id]
                    label = next((key for key, sid in citations.items() if sid == item.source_id), None)
                    if label is None:
                        label = str(len(citations) + 1)
                        citations[label] = item.source_id
                    text += f"\n  - {assessment.relation}: {escape_markdown(item.excerpt)} [{label}]"
            (unresolved if claims[result.claim_id].priority == 'high' else optional).append(text)
        if any(item.relation != "supports" and item.evidence_id in claims[result.claim_id].evidence_ids
               for result in verifications for item in result.passage_assessments):
            uncertainties.append("Some attached passages do not support their claims; see passage_assessments in JSON output.")
        if len(supported_source_ids) < 2:
            uncertainties.append("Fewer than two sources supplied supported evidence.")
        checks_passed = (
            bool(sentences) and not state["rejected_evidence"]
            and not rejected_verifications and len(supported_source_ids) >= 2
            and state["step_status"]["planner"] == "completed"
            and state["step_status"]["evidence"] == "completed"
            and state["step_status"]["verification"] == "completed"
            and not state["usage"].limit_reason
        )
        status = 'insufficient_evidence'
        if checks_passed:
            status = ('complete' if state['coverage_sufficient'] and not unresolved and not optional
                      else 'partial')
        uncertainties = list(dict.fromkeys(uncertainties))
        step_status = {name: "skipped" if status == "pending" else status
                       for name, status in state["step_status"].items()}
        step_status["writer"] = "completed"
        introduction = {
            'complete': 'The following findings answer the question using claims checked against retrieved passages.',
            'partial': 'Supported answer with limitations. The findings below have checked support; unresolved gaps remain and the answer may not cover the full question.',
            'insufficient_evidence': 'Insufficient evidence to answer the research question reliably. Any findings below are limited to the checked support available.',
        }[status]
        if self.settings.mock_mode:
            introduction = "MOCK SAMPLE — " + introduction
        uncertainty_section = "## Uncertainty\n\n" + "\n".join(f"- {escape_markdown(item)}" for item in uncertainties)
        report = ResearchReport(
            query=state["question"], title="Research summary",
            status=status,
            search_queries=list(state["searched_queries"]), research_plan=state["plan"],
            step_status=step_status, research_iteration=state["iteration"],
            body_markdown="\n\n".join([introduction, *(['## Findings', *paragraphs] if paragraphs else []),
                                       *(['## Source-specific examples', *examples] if examples else []),
                                       *( ["## Unresolved claims\n\n" + "\n".join(unresolved)] if unresolved else []),
                                       *( ["## Optional gaps\n\n" + "\n".join(optional)] if optional else []),
                                       uncertainty_section]),
            sources=list(state["sources"]), evidence=list(evidence.values()), claims=verifications,
            citations=citations, limitations=uncertainties, uncertainties=uncertainties,
            usage=state["usage"].model_dump(),
        )
        return {"report": report, "uncertainties": uncertainties, "step_status": step_status}
